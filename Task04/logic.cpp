//O(N)
void swap_extrem_elements(int array[], int size) {
    if (size <= 1) {
        return;
    }

    
    int min_idx = 0;
    int max_idx = 0;

   
    for (int i = 1; i < size; i++) {
        
        if (array[i] >= array[max_idx]) {
            max_idx = i;
        }
        if (array[i] <= array[min_idx]) {
            min_idx = i;
        }
    }

    
    int temp = array[min_idx];
    array[min_idx] = array[max_idx];
    array[max_idx] = temp;



}

