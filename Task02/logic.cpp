//O(N)
double find_sum(int* array, int size) {
	double sum = 0.0;
	for (int i = 0; i < size; i++) {
		sum += array[i];
	}
	double avg =  sum / size;
	int total = 0;
	for (int i = 0; i < size; i++) {
		if (array[i] < avg) {
			total += array[i];
		}
	}
	return total;
}

