#include "logic.h"
//O(N^2)
bool is_the_same_elements(int array[], int size) {
	for (int i = 0; i < size - 1; ++i) {
		for (int j = i + 1; j < size; ++j) {
			if (array[i] == array[j]) {
				return true;
			}
		}
	}

	return false;
}
