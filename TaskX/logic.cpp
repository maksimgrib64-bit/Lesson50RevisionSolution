//O(N)
void reverse(int array[], int size, int a, int b) {
    if (size <= 0) {
        return;
    }

    
    if (a < 0 || b < 0) {
        return;
    }

   
    if (a >= size || b >= size) {
        return;
    }

   
    if (a > b) {
        swap(a, b); 
    }

   

    while (a < b) {
        swap(array[a], array[b]); 

        a = a + 1;
        b = b - 1;
    }
}

