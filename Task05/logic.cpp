#include "logic.h"

//O(N)
void reverse(int* array, int size) {
	int n = size / 2;
	for (int i = 0; i < n; i++) {
		int t = array[i];
		array[i] = array[size - 1 - i];
		array[size - 1 - i] = t;

	}
}
